<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Feedback Density</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Feedback density is the number of corrections, suggestions, and targeted comments a teacher can give each student per session. In writing, it is the difference between reading every sentence a child writes and skimming a paragraph. In speaking, it is the difference between correcting a grammar error in the moment and letting it pass because there are nineteen other hands up.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In a class of 20, a teacher might give each child two or three meaningful corrections per session. In a class of 6, that number rises to ten or fifteen. Over a school year of 80 sessions, the difference compounds dramatically: roughly 200 corrections in a large class versus 1,000 in a small one. This is not a subtle pedagogical nuance. It is a five-times difference in the volume of targeted feedback a child receives.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Error Correction Timing</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There is a window in language learning called the "correction window." When a child makes an error, the most effective correction happens within seconds, while the child still remembers what they said and why. In a large class, errors pass uncorrected because the teacher is attending to someone else. In a small class, the teacher catches the error in the moment, corrects it, and the child integrates the correction immediately.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>This matters more than parents typically realize. Uncorrected errors become habits. A child who says "I have been to there" three hundred times without correction will find it significantly harder to unlearn than a child who was corrected the first or second time. Small classes are not just more pleasant. They are structurally different in how they handle the mechanics of language acquisition.</p>
<!-- /wp:paragraph -->
