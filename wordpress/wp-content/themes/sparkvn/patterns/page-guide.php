<!-- wp:heading -->
<h2 class="wp-block-heading">The Basic Math</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"lead"} -->
<p class="lead">Speaking Time, Feedback Density, and Error Correction</p>
<!-- /wp:paragraph -->

<!-- wp:separator {"className":"rule-gold"} -->
<hr class="wp-block-separator has-alpha-channel-opacity rule-gold"/>
<!-- /wp:separator -->
</div>
<!-- /wp:group -->

<!-- wp:group {"className":"copy","style":{"spacing":{"margin":{"top":"1.6rem"}}}} -->
<div class="wp-block-group copy" style="margin-top:1.6rem">
<!-- wp:paragraph -->
<p>Language learning is not like learning math or history. You cannot learn a language by listening. You learn by producing language, making mistakes, and having those mistakes corrected in real time. This is well established in second language acquisition research and is the foundation of communicative language teaching. The implication for class size is direct and mathematical.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Speaking Time</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In a 90-minute English session, a teacher needs to explain, demonstrate, and manage transitions. In practice, roughly 50 to 60 minutes of a session involve student production: speaking, writing, reading aloud, or answering questions. In a class of 20 students, that is roughly 2.5 to 3 minutes of individual speaking time per child. In a class of 6, it is 8 to 10 minutes. This is not a marginal difference. It is a threefold increase in the single most important activity for language acquisition.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>For a child who is shy, or who is at a lower level than their peers, 2.5 minutes is often zero. They can sit through an entire session in a large class without producing a single sentence, and neither the teacher nor the parent may know. In a class of six, the teacher hears every child, every session. There is nowhere to hide, and no child needs to.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->

