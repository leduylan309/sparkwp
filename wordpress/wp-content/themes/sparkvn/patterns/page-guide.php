<h2 class="wp-block-heading">What The Research Actually Says</h2>
<!-- /wp:heading -->

<!-- wp:separator {"className":"rule-gold"} -->
<hr class="wp-block-separator has-alpha-channel-opacity rule-gold"/>
<!-- /wp:separator -->
</div>
<!-- /wp:group -->

<!-- wp:group {"className":"copy","style":{"spacing":{"margin":{"top":"1.6rem"}}}} -->
<div class="wp-block-group copy" style="margin-top:1.6rem">
<!-- wp:paragraph -->
<p>Parents deserve to know that the research on class size is more nuanced than either side of the debate typically presents. The honest summary is this: reducing class size from 25 to 20 produces small, inconsistent effects. Reducing class size from 15 to 8, or from 8 to 4, produces meaningful and consistent effects, particularly for younger children and children from non-English-speaking backgrounds.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The STAR Study</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The most cited class-size research is the Tennessee STAR study (Student/Teacher Achievement Ratio), conducted across 79 schools from 1985 to 1989. It compared classes of 13 to 17 students (small) against classes of 22 to 25 students (regular). The findings showed statistically significant improvements in reading for students in smaller classes, with the strongest effects in the early grades and among minority and low-income students. The gains persisted into later years even after students returned to regular-sized classes.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The STAR study is important but has a limitation for our context: its "small" classes were 13 to 17 students, which is still larger than what specialist English centers offer. The study tells us that reducing class size matters. It does not tell us much about what happens below 10 students, which is where the most interesting effects for language learning occur.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The Language-Specific Research</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Language learning benefits disproportionately from small classes compared to other subjects. This is because language acquisition requires production and feedback, not just comprehension. Several studies in the second language acquisition literature have documented this.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The relationship between class size and oral participation is not linear. It follows a threshold pattern. Below about 8 students, every child speaks in every session. Between 8 and 15, participation drops to roughly half the class. Above 15, a small number of confident students dominate and the rest are effectively silent. For English as a second or additional language, where oral production is essential to progress, this threshold effect means that classes above 8 students are structurally limiting for the quieter half of the room.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Writing feedback follows a similar pattern. A teacher can read and provide detailed feedback on writing from 6 students in a 90-minute session. They cannot do the same for 15. At best, they skim. The child receives a tick or a grade, not the sentence-level correction that drives improvement.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The Honest Caveats</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The research also shows that class size alone is not sufficient. A small class with a poor teacher does not outperform a large class with an excellent teacher. Class size sets the ceiling; teacher quality determines where within that ceiling the outcomes fall. This is why Spark combines small class size with specialist teaching. Neither alone is enough.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There is also a floor below which smaller classes stop adding value for typical learners. One-on-one instruction removes the peer dynamic that helps children acquire language through interaction, modeling, and social motivation. A child alone with a teacher does not hear other children making and correcting mistakes, does not practice the turn-taking and listening that group communication requires, and does not benefit from the "eavesdropping effect" where they learn from corrections given to a peer. The research on language learning in particular suggests that 3 to 6 students is the range where both individual attention and peer dynamics are fully present.</p>
<!-- /wp:paragraph -->
