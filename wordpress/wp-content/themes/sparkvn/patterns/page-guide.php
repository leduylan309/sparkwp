<h2 class="wp-block-heading">The Six-Student Threshold</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"lead"} -->
<p class="lead">Why Spark Chose Six</p>
<!-- /wp:paragraph -->

<!-- wp:separator {"className":"rule-gold"} -->
<hr class="wp-block-separator has-alpha-channel-opacity rule-gold"/>
<!-- /wp:separator -->
</div>
<!-- /wp:group -->

<!-- wp:group {"className":"copy","style":{"spacing":{"margin":{"top":"1.6rem"}}}} -->
<div class="wp-block-group copy" style="margin-top:1.6rem">
<!-- wp:paragraph -->
<p>The number six is not arbitrary. It is the result of a specific set of structural requirements that we believe are non-negotiable for effective English language instruction.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At six students, a teacher can hear every child read aloud in every session. This matters for phonics, for reading comprehension, and for identifying decoding errors that a child might mask in a larger group by mumbling or staying silent.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At six students, a teacher can read every piece of writing carefully and provide detailed, sentence-level feedback. Not "good work" or a grade, but specific comments: "This sentence needs a conjunction," "Your vocabulary here is strong but the tense is wrong," "Try restructuring this paragraph with the topic sentence first."</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At six students, a teacher can correct speaking errors in real time, in the correction window, without losing the attention of the rest of the group. Beyond six, the teacher begins to choose between correcting the speaker and managing the group. That choice is the structural moment where large-class teaching diverges from small-class teaching.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At six students, diagnostic grouping works. The teacher can hold in mind the specific profile of each child: where they are strong, where they are weak, what they need next. Beyond six, the profiles begin to blur and teaching shifts from individual responsiveness to group management.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>At six students, shy or anxious children participate. The social pressure of a larger group keeps many children silent. In a group of six, the social dynamic shifts from "audience and performers" to "conversation among peers." This is particularly important for children who are already anxious about their English.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We have experimented with groups of eight and found that the quality of feedback begins to degrade. We have worked with groups of four and found that the peer dynamic is thinner. Six is the number where both individual feedback and group dynamics are fully present. It is not the cheapest structure to deliver. It is the most effective one.</p>
<!-- /wp:paragraph -->
</div>
