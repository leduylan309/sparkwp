<h2 class="wp-block-heading">FAQs</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"lead"} -->
<p class="lead">Frequently asked questions about class size and English learning</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->

<!-- wp:group {"className":"faq-list"} -->
<div class="wp-block-group faq-list">
<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Does class size really matter that much, or is teacher quality more important?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Both matter, but they interact. A great teacher in a class of 20 is constrained by the math: they cannot give each child enough speaking time, writing feedback, or real-time correction. A mediocre teacher in a class of 6 still gives more individual attention than most teachers can in a class of 20. The ideal is a great teacher in a small class. Class size sets the ceiling; teacher quality determines how close you get to it.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>My child is at ILA and seems to enjoy it. Should I switch to a smaller class?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Not necessarily. If your child is making the progress you expected and the goals are conversational rather than academic, a chain center may be the right fit. The class size question becomes critical when your child needs targeted academic English development, structured writing improvement, or IELTS preparation where every error corrected matters.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Is one-on-one tutoring better than a small group?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>For language learning, usually not. One-on-one removes the peer dynamic that is particularly important for language acquisition: hearing other children speak, practicing turn-taking, learning from peers' mistakes, and the social motivation of a small group. One-on-one is valuable for very specific needs (dyslexia support, advanced acceleration, short-term exam coaching), but for ongoing English development, a small group of 4 to 6 is structurally stronger.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>What does &quot;small class&quot; mean at Spark?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Maximum six students. This is a hard cap, not an average. We do not add a seventh student to an existing class. If a class is full at six, we open a new group or place the child on a waitlist until a suitable group forms.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Why not cap at four instead of six?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Groups of four work well but produce a thinner peer dynamic. With four students, the conversational range narrows and the interaction patterns become less varied. Six gives enough social complexity for genuine group communication while still allowing full individual attention.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>My child is shy. Will a small group help or make things worse?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Almost always better. Shy children in large classes often go silent because the social risk of speaking in front of 15 or 20 peers is too high. In a group of six, the dynamic is conversational rather than performative. Shy children begin speaking within weeks, often surprising their parents.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>How does class size affect IELTS preparation specifically?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>IELTS requires precision in writing and fluency in speaking, both of which depend on high-frequency error correction and extensive practice. In a class of 15, a student might write one practice essay per session and receive general feedback. In a class of six, they write the same essay and receive sentence-level correction across grammar, vocabulary, coherence, and task achievement. This is one of the reasons over 95% of Joe Evans' IELTS students at Spark achieve Band 7.5 or higher.</p>
<!-- /wp:paragraph -->
</div>
