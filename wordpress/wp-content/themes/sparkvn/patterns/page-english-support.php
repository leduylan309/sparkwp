<h2 class="wp-block-heading">FAQs</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"lead"} -->
<p class="lead">Frequently asked questions about choosing an English center in HCMC</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->

<!-- wp:group {"className":"faq-list cols-2"} -->
<div class="wp-block-group faq-list cols-2">
<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>What is the most important factor when choosing an English center for an international school child?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Class size. Everything else (teacher quality, curriculum, progress reporting) flows from class size structurally. A great teacher in a class of fifteen cannot deliver the same individual attention and differentiation as a competent teacher in a class of six. Class size sets the ceiling on what is possible. Other factors raise or lower the level within that ceiling.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Should I choose the closest English center or travel further for a better fit?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Within reason, fit beats convenience. Twice-weekly sessions over an academic year is roughly 80 to 100 sessions. Better-fit instruction across that volume produces meaningfully better outcomes than mediocre instruction. That said, if travel adds an hour each way, schedule strain often kills consistency. The sweet spot is the best-fit center within a reasonable commute. For families in Thao Dien and the surrounding international school community, that often means a Thao Dien-based specialist.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Is a more expensive center always better?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>No. Some expensive centers are over-priced for what they deliver. Some moderately priced centers are excellent. The pricing is a signal but not a proxy for quality. Use the framework above (class size, teacher specialism, diagnostic process, curriculum alignment, progress reporting) to evaluate, then check whether the pricing matches the value those structural factors deliver.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>How do I know if my child is making real progress at an English center?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Two ways. First, the center should give you specific progress measurements every six to eight weeks across multiple skills (reading age, writing development, vocabulary, listening, speaking). Vague "improving nicely" feedback is not measurement. Second, look for transfer effects: is your child's school work in English-medium subjects improving? Are their school reports getting stronger? Real English progress shows up in school outcomes within two to three terms, not just in center-internal assessments.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Should I switch English centers if my child is not progressing?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>First, ask the center directly: why is my child not progressing, and what would change? A serious center will give you a specific diagnostic answer. If the answer is vague, switch. If the answer is specific and the proposed change makes sense, give it one term to work. If the change does not produce measurable progress, switch. Sticking with a center out of inertia or sunk cost rarely produces a different outcome.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>Are online English programs (Cambly, Preply, online tutors) a good alternative to a center?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>For some specific needs, yes. Online tutors can be excellent for additional speaking practice or for short-term exam-specific coaching. They are usually less effective for systematic curriculum-aligned development across multiple skills, and they offer no peer dynamic. The right answer is often a combination: a primary in-person program with structure, plus targeted online support for specific needs.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>My child has been at ILA for three years and I&#x27;m not sure they need to switch. How do I decide?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Ask: are they making the progress you expected when you enrolled? If yes, stay. If no, ask the center directly what is causing the slowdown and what they plan to change. If the answer is satisfying, give it one term. If the answer is unsatisfying or progress continues to stall, look at specialist alternatives. Many international school families come to Spark after exactly this period at a chain center and we can usually identify the specific blocker quickly.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>What about reviews online? Are they reliable?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Use them carefully. Specific, detailed reviews from clearly identifiable parents are useful. Vague positive reviews and vague negative reviews are not. Where possible, ask other parents in your child's school community directly. Word of mouth in international school parent groups is more reliable than online review aggregators.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>How do I know if a small-group center is actually delivering on its small-group claim?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Ask to observe a class. If they decline, that is a signal. If they agree, watch the actual class size, watch how the teacher gives feedback, watch how each child is engaged. A small group that is actually a small group will look different from a large class with a "small group" label.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary>When should I start looking for outside English support?<span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Earlier than parents typically do. The most common pattern we see is parents waiting until a school report flags an issue, by which time the gap has been there for at least a term or two. If you notice early signals (reading age dropping, writing not developing, speaking confidence dropping), it is worth doing a free assessment to know where things stand. Better to act when the gap is small than when it has compounded.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

