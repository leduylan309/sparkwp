<p class="label"><span class="spark"></span>What is reading age?</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Reading age is an assessment measure that compares a student’s reading ability to typical expectations for different age groups. A student may be reading <b>below</b>, <b>at</b>, or <b>above</b> their chronological age.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Reading age is not a measure of intelligence. It provides insight into a student’s current reading development and helps identify whether additional support may be beneficial. It is only one part of the overall literacy picture — fluency, vocabulary, comprehension, writing, and critical thinking matter too.</p>
