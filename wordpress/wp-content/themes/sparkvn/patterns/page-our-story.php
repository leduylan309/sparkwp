<p>Spark was founded in 2019 with a simple observation: too many children at good schools were still struggling with English.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Not because they lacked ability. Because nobody had taken the time to find the specific gap and close it properly.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
