<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Red flags worth taking seriously</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>None of these alone is disqualifying, but combined they should slow you down.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->

<!-- wp:list {"className":"flag-list"} -->
<ul class="wp-block-list flag-list"><!-- wp:list-item -->
<li><b>Promised band scores or grades.</b> No center can promise an IELTS 8.0 or an IB 7. The honest version is measurable progress over an appropriate timeframe.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><b>Hedging on class size, credentials or pricing.</b> A center that hedges on basic questions is hedging on the questions that matter.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><b>Pressure tactics.</b> "Sign up today for a discount." "Only two spaces left." Specialist centers do not need scarcity tactics.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><b>Generic curriculum claims.</b> "We follow international standards" is not a curriculum. Naming Cambridge YLE, IGCSE and IB specifications is.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><b>No progress measurement.</b> If they cannot say how progress is measured over six months, it is not being measured.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><b>Too-good-to-be-true pricing.</b> Specialist small-group at chain prices means bigger classes, less qualified teachers or a thinner curriculum. Pick which.</li>
<!-- /wp:list-item --></ul>
