<!-- wp:heading -->
<h2 class="wp-block-heading">The Evaluation Framework</h2>
<!-- /wp:heading -->

<!-- wp:separator {"className":"rule-gold"} -->
<hr class="wp-block-separator has-alpha-channel-opacity rule-gold"/>
<!-- /wp:separator -->
</div>
<!-- /wp:group -->

<!-- wp:paragraph {"className":"lead"} -->
<p class="lead">When you have shortlisted two or three options, evaluate them across the seven dimensions that actually matter. The question is not "which has the best marketing" but "which structurally delivers what my child needs."</p>
<!-- /wp:paragraph -->

<!-- wp:group {"className":"faq-list crit-list"} -->
<div class="wp-block-group faq-list crit-list">
<!-- wp:details {"className":"is-style-faq faq-item","showContent":true} -->
<details class="wp-block-details is-style-faq faq-item" open><summary><span class="n">1</span><span class="t">Class size<small>Ask the actual maximum, not the average.</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Many centers advertise "small classes" and mean 8 to 12. Some mean 15. Six is the threshold above which differentiated instruction becomes structurally difficult: a teacher cannot reliably hear every child speak in every session or give meaningful written feedback on every piece of work. We have a <a href="/class-size/">separate piece on the research behind this</a>. A center that hedges or gives a range is telling you something.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">2</span><span class="t">Teacher specialism<small>Who specifically will teach my child?</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>What are their specific qualifications? Are they an IB specialist? An IGCSE specialist? A phonics specialist? Have they worked in international school environments? "Native speaker" is not a qualification. "TEFL certified" is a baseline, not a specialism.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">3</span><span class="t">Diagnostic process<small>How do you assess my child before placing them?</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>A serious center assesses across multiple skill areas (reading age, writing, speaking, listening, vocabulary) before recommending placement. If a center wants to enroll without a real diagnostic, their grouping is by registration date rather than by ability. Fine for some children, a problem for others — know which you are choosing.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">4</span><span class="t">Curriculum alignment<small>How does your curriculum align to my child's school?</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>A center using generic textbooks is not aligned to anything specific. A center that can name the IB English specification, the IGCSE English Language curriculum or the Cambridge Young Learners progression is doing curriculum work that compounds.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">5</span><span class="t">Progress reporting<small>How often, how detailed, which skills?</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Vague summary feedback is a sign the center is not measuring outcomes. Detailed reports across multiple skills, every six to eight weeks, with specific observations, show the underlying assessment work is being done.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">6</span><span class="t">Trial class or assessment<small>Use it — and watch.</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Look for how much speaking time your child gets, how the teacher gives feedback, how the class is structured, whether there is differentiation between students. Children are unreliable about whether they "liked" a class but reliable about whether they understood it.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq faq-item"} -->
<details class="wp-block-details is-style-faq faq-item"><summary><span class="n">7</span><span class="t">Pricing transparency<small>Ask for the full pricing in writing.</small></span><span class="q-ic"></span></summary>
<!-- wp:group {"className":"faq-a"} -->
<div class="wp-block-group faq-a">
<!-- wp:paragraph -->
<p>Annual, term and per-session. What is included, what is extra, what the cancellation terms are. Almost no English center in HCMC publishes prices — a category-wide failure of trust. Treat willingness to be transparent about pricing as a signal of how the center treats parents in general.</p>
<!-- /wp:paragraph -->
</div>
<!-- /wp:group -->
</details>
<!-- /wp:details -->
</div>
